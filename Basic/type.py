# Type
# Type is a way to classify data in programming. 
# It determines what kind of value a variable can hold and what operations can be performed on it.
# There are different types of data, such as integers, floats, strings, and booleans.
#  Integers are whole numbers without a decimal point.
# Floats are numbers with a decimal point.
# Strings are sequences of characters enclosed in quotes.
# Booleans are values that can be either True or False.
x = 5
print(type(x))
y = 3.14
print(type(y))
z = "Hello, World!"
print(type(z))
w = True
print(type(w))