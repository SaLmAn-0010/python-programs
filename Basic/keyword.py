# Keyword
# Keywords are reserved words in Python that have special meanings and purposes.
# They cannot be used as identifiers (variable names, function names, etc.).
# Some common keywords in Python include: and, as, assert, break, class,
#  continue, def, del, elif, else, except, exec, finally, for, from, global, if, import, in, is,
#  lambda, not, or, pass, print, raise, return, try, while, with, yield
# Example of using keywords
