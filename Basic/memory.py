
# Memory
# Memory is a place where we can store data and information. 
# It is a temporary storage area that can be accessed by the computer's processor.
#  Memory is used to store data and instructions that are needed for the computer to perform tasks.
# There are different types of memory, such as RAM (Random Access Memory), 
# ROM (Read-Only Memory), and Cache Memory.
#  RAM is used for temporary storage of data and instructions that are currently being used by the computer. 
# ROM is used for permanent storage of data and instructions that are needed for the computer to boot up.
#  Cache Memory is a small amount of memory that is used to store frequently accessed data and instructions for faster access.
