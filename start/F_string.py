# F-strings in Python
# An f-strings is a convenient way to insert variables and expressions            directiy inside by string.

# with f-strings
name = "Salman"
age = 30
print(f"Hello, my name is {name} and I am {age} years old.")

#without f-strings
name = "Salman"
age = 30
print("My name is ", name , "and I am", age, "years old.")