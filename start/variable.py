# Variable:- A container for value (string,integer,float,boolean) A variable behaves as if it was the value it contains

#String :- A string is a series of characters .they can include numbers but we treat them as character .

First_name = "Salman"
print(f"Hello {First_name}")

#integer :- An integer is a whole number 

age = 22
print(f"I am {age} years old")

# Float :- A float is a number but it contains a decimal portion.

price = 100.54
print(f"the price is ${price}")

# Boolean :- A boolean is either true or false

is_student = True
print(f"Are you a student? {is_student}")
