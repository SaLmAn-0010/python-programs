#Typecasting is the process of converting a variable from one data type to another.
#  In Python, you can use built-in functions to perform typecasting.
#  Here are some common typecasting functions:
# 1. int(): Converts a value to an integer.
# 2. float(): Converts a value to a floating-point number.
# 3. str(): Converts a value to a string.
# 4. bool(): Converts a value to a boolean.

name = "Salman Ansari"
age = 22
gpa = 3.75
is_student = True
type(name)  # Output: <class 'str'>
type(age)   # Output: <class 'int'> 
type(gpa)   # Output: <class 'float'>
type(is_student)  # Output: <class 'bool'>
print(type(name))
print(type(age))
print(type(gpa))
print(type(is_student))