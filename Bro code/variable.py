#variable: a concept used to store data in programming.
#  It is a named location in memory that holds a value which can be changed during program execution.
#  Variables are essential for storing and manipulating data in a program.

#string: a data type used to represent text.
#  It is a sequence of characters enclosed in quotes (single or double).
#  Strings can contain letters, numbers, symbols, and whitespace.

first_name = "Salman"
print(f"Hello {first_name}!")
home_town = "Bokaro steel city"
print(f"My home town is {home_town}.")
emailID = "salman@example.com"
print(f"My email is {emailID}.")

#integer: a data type used to represent whole numbers.
#  Integers can be positive, negative, or zero, and they do not have decimal points.
age = 25    
print(f"I am {age} years old.")
weight = 70
print(f"My weight is {weight} kg.")
item_count = 10
print(f"I have {item_count} items in my bag.")

#float: a data type used to represent numbers with decimal points.
#  Floats can represent both whole numbers and fractional values.
price = 19.99
print(f"The price of the item is ${price}.")
temperature = 36.5
print(f"The current temperature is {temperature}°C.")
population = 7.8e9
print(f"The world population is approximately {population} people.")


#boolean: a data type used to represent truth values.
#  It can have one of two possible values: True or False.   
is_student = True
if is_student:
    print("I am a student.")
else:
    print("I am not a student.")
for_sale = False
if for_sale:
    print("The item is for sale.")
else:
    print("The item is not for sale.")
is_online = True
if is_online:
    print("I am online.")   
else:
    print("I am offline.")
    


