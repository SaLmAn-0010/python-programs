# Arithmetic operations
print(5 + 3)  # Addition
print(5 - 3)  # Subtraction
print(5 * 3)  # Multiplication
print(5 / 3)  # Division
print(5 % 3)  # Modulus
print(5 ** 3) # Exponentiation

Salman = 10
Salman += 5  # Increment by 5
print(Salman)  # Output: 15
Salman -= 3  # Decrement by 3
print(Salman)  # Output: 12
Salman *= 2  # Multiply by 2
print(Salman)  # Output: 24
Salman /= 4  # Divide by 4
print(Salman)  # Output: 6.0
Salman %= 4  # Modulus by 4
print(Salman)  # Output: 2.0
Salman **= 3  # Raise to the power of 3
print(Salman)  # Output: 8.0
Salman //= 2  # Floor division by 2
print(Salman)  # Output: 4.0
Salman = 10 
